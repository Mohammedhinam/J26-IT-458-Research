"""Generated-only lossless JPEG qualification. No paths, dataset IO or export CLI.

The caller supplies generated bytes and a separately reviewed ICC hash allowlist.
No real-source profile is approved by this module or its tests.
"""
from hashlib import sha256
import io
from pathlib import PurePosixPath
import warnings
import xml.etree.ElementTree as ET

import numpy as np
from PIL import Image, ImageCms

VERSION = 'generated-jpeg-metadata-v1'
MAX_BYTES = 100 * 1024**2
ICC = b'ICC_PROFILE\0'
XMP = b'http://ns.adobe.com/xap/1.0/\0'
CODING = {0xC0, 0xC4, 0xDB, 0xDD}


def digest(value):
    return sha256(value).hexdigest()


def segment(marker, payload):
    if len(payload) > 65533:
        raise ValueError('JPEG segment too large')
    return b'\xff' + bytes([marker]) + (len(payload) + 2).to_bytes(2, 'big') + payload


def parts(raw):
    """Accept one baseline RGB8 scan; reject trailing data or hidden extra scans."""
    if type(raw) is not bytes or not 20 <= len(raw) <= MAX_BYTES or raw[:2] != b'\xff\xd8':
        raise ValueError('Expected bounded JPEG bytes')
    result, offset, frame = [], 2, None
    while offset + 4 <= len(raw):
        if raw[offset] != 255:
            raise ValueError('Malformed JPEG marker')
        marker = raw[offset + 1]
        length = int.from_bytes(raw[offset + 2:offset + 4], 'big')
        end = offset + 2 + length
        if marker in {0, 1, 0xD8, 0xD9, 255} or 0xD0 <= marker <= 0xD7 or length < 2 or end > len(raw):
            raise ValueError('Invalid JPEG segment framing')
        payload = raw[offset + 4:end]
        if marker == 0xC0:
            if frame is not None or len(payload) != 15 or payload[0] != 8 or payload[5] != 3:
                raise ValueError('Only baseline eight-bit three-component JPEG supported')
            height, width = int.from_bytes(payload[1:3], 'big'), int.from_bytes(payload[3:5], 'big')
            if min(width, height) <= 0 or max(width, height) > 16384 or width * height > 40_000_000:
                raise ValueError('Image geometry exceeds qualification bounds')
            frame = (width, height)
        if marker == 0xDA:
            if frame is None or len(payload) != 10 or payload[0] != 3 or payload[-3:] != b'\0\x3f\0':
                raise ValueError('Unsupported JPEG scan')
            position = end
            while position < len(raw):
                found = raw.find(b'\xff', position)
                if found < 0 or found + 1 >= len(raw):
                    raise ValueError('Missing JPEG EOI')
                code = raw[found + 1]
                if code == 0 or 0xD0 <= code <= 0xD7:
                    position = found + 2
                elif code == 0xD9 and found + 2 == len(raw):
                    return result, raw[offset:], frame
                else:
                    raise ValueError('Extra scan, post-scan metadata or trailing data rejected')
            raise ValueError('Truncated JPEG scan')
        if marker not in CODING and not 0xE0 <= marker <= 0xEF and marker != 0xFE:
            raise ValueError('Unsupported coding marker')
        result.append((marker, payload))
        offset = end
    raise ValueError('Missing JPEG scan')


def profile_from(segments, trusted_profiles):
    chunks, total = {}, None
    for marker, payload in segments:
        if marker != 0xE2:
            continue
        if not payload.startswith(ICC) or len(payload) <= 14:
            raise ValueError('Unknown APP2 or malformed ICC chunk')
        number, count = payload[12:14]
        if not 1 <= number <= count or number in chunks or (total is not None and total != count):
            raise ValueError('Inconsistent ICC chunk sequence')
        total = count
        chunks[number] = payload[14:]
    if total is None or set(chunks) != set(range(1, total + 1)):
        raise ValueError('Missing or incomplete ICC')
    raw = b''.join(chunks[index] for index in range(1, total + 1))
    if digest(raw) not in trusted_profiles:
        raise ValueError('ICC not independently allowlisted as non-identifying')
    # CMS parsing is a structural check; privacy review is a separate prerequisite.
    try:
        profile = ImageCms.ImageCmsProfile(io.BytesIO(raw))
        if profile.profile.xcolor_space.strip() != 'RGB':
            raise ValueError('Only RGB ICC supported')
    except Exception as error:
        raise ValueError('Malformed or unsupported ICC') from error
    return raw


def metadata_only_xmp(payload):
    """Do not silently remove XMP colour/orientation/HDR rendering directives."""
    xml = payload[len(XMP):]
    if b'<!DOCTYPE' in xml.upper() or b'<!ENTITY' in xml.upper():
        raise ValueError('Unsafe XML declarations')
    allowed = {
        'adobe:ns:meta/': {'xmpmeta'},
        'http://www.w3.org/1999/02/22-rdf-syntax-ns#': {'RDF', 'Description', 'about', 'Bag', 'Seq', 'Alt', 'li'},
        'http://www.w3.org/XML/1998/namespace': {'lang'},
        'http://purl.org/dc/elements/1.1/': {'creator', 'description', 'rights', 'title', 'subject'},
        'http://ns.adobe.com/xap/1.0/': {'CreateDate', 'ModifyDate', 'MetadataDate', 'CreatorTool'},
        'http://ns.adobe.com/xap/1.0/mm/': {'DocumentID', 'InstanceID', 'OriginalDocumentID'},
    }
    try:
        root = ET.fromstring(xml)
        for element in root.iter():
            for name in [element.tag, *element.attrib]:
                if not name.startswith('{') or '}' not in name:
                    raise ValueError('Unknown XMP schema')
                namespace, local = name[1:].split('}', 1)
                if local not in allowed.get(namespace, set()):
                    raise ValueError('Unqualified XMP/rendering schema')
    except ET.ParseError as error:
        raise ValueError('Malformed XMP') from error


def binding(record):
    """Preserve generated ID/filename/split/annotation association, never grades."""
    filename = record['filename']
    path = PurePosixPath(filename)
    split = record['original_split']
    if (split not in {'Training', 'Validation'} or path.name != filename
            or path.suffix.lower() != '.jpg' or '\\' in filename or ':' in filename
            or record['image_id'] != split + '/' + path.stem
            or record['caption_filename'] != filename
            or record['annotation_filename'] != path.stem + '.txt'
            or record['review_status'] != 'pending'):
        raise ValueError('Unsafe or mismatched generated annotation binding')
    return {key: record[key] for key in ['image_id', 'filename', 'original_split',
            'caption_filename', 'annotation_filename', 'review_status']}


def strip_generated(raw, expected_source_sha, trusted_profiles, record):
    """Return generated sanitised bytes; never save or re-encode a JPEG."""
    if digest(raw) != expected_source_sha:
        raise ValueError('Source SHA mismatch')
    identity = binding(record)
    segments, scan, dimensions = parts(raw)
    profile = profile_from(segments, trusted_profiles)
    kept, removed = [], []
    for marker, payload in segments:
        if marker in CODING or marker == 0xE2:
            kept.append(segment(marker, payload))
        elif marker == 0xE0:
            if (not payload.startswith(b'JFIF\0') or len(payload) < 14
                    or len(payload) != 14 + 3 * payload[12] * payload[13]):
                raise ValueError('Unknown APP0/thumbnail format')
            kept.append(segment(marker, payload[:12] + b'\0\0'))
            if payload[12:14] != b'\0\0': removed.append('JFIF_thumbnail')
        elif marker == 0xEE:
            if len(payload) != 12 or payload[:7] != b'Adobe\0d' or payload[7:11] != bytes(4) or payload[11] not in (0, 1):
                raise ValueError('Unknown Adobe colour-transform segment')
            kept.append(segment(marker, payload))
        elif marker == 0xE1 and payload.startswith(b'Exif\0\0'):
            removed.append('EXIF')
        elif marker == 0xE1 and payload.startswith(XMP):
            metadata_only_xmp(payload)
            removed.append('XMP')
        elif marker == 0xFE:
            removed.append('COM')
        else:
            raise ValueError('Unknown APP metadata may affect rendering; no silent stripping')
    if removed.count('EXIF') > 1:
        raise ValueError('Duplicate EXIF containers')
    # Header parse checks orientation before its EXIF container is discarded.
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter('always')
        with Image.open(io.BytesIO(raw)) as image:
            if image.mode != 'RGB' or image.size != dimensions or image.getexif().get(274, 1) != 1:
                raise ValueError('RGB/geometry/orientation not qualified')
            if 'EXIF' in removed and not image.getexif():
                raise ValueError('Malformed EXIF container')
        if caught:
            raise ValueError('Image/header warning; stop rather than guess')
    output = b'\xff\xd8' + b''.join(kept) + scan
    receipt = verify_generated_pair(raw, output, expected_source_sha, trusted_profiles, identity)
    receipt['removed_containers'] = removed
    return output, receipt


def verify_generated_pair(source, output, expected_source_sha, trusted_profiles, record):
    """Independently decode generated source/output and verify zero pixel change."""
    if digest(source) != expected_source_sha:
        raise ValueError('Source SHA mismatch')
    identity = binding(record)
    before, scan_before, size_before = parts(source)
    after, scan_after, size_after = parts(output)
    profile = profile_from(before, trusted_profiles)
    if (profile != profile_from(after, trusted_profiles) or scan_before != scan_after
            or size_before != size_after
            or [p for p in before if p[0] in CODING | {0xEE}] != [p for p in after if p[0] in CODING | {0xEE}]):
        raise ValueError('Image coding/scan/ICC/geometry changed')
    if ([p[:12] for m, p in before if m == 0xE0]
            != [p[:12] for m, p in after if m == 0xE0]):
        raise ValueError('JFIF display geometry changed')
    for marker, payload in after:
        if marker == 0xE0:
            if len(payload) != 14 or payload[:5] != b'JFIF\0' or payload[12:] != b'\0\0':
                raise ValueError('Unsafe JFIF output')
        elif marker not in CODING | {0xE2, 0xEE}:
            raise ValueError('Metadata survived sanitisation')
    # Identical RGB arrays plus identical ICC preserve the declared colour
    # interpretation. This is not proof of clinical/camera colour accuracy.
    with Image.open(io.BytesIO(source)) as original, Image.open(io.BytesIO(output)) as cleaned:
        if original.mode != 'RGB' or cleaned.mode != 'RGB':
            raise ValueError('Unexpected decoded mode')
        a, b = np.asarray(original), np.asarray(cleaned)
        if original.getexif().get(274, 1) != 1 or cleaned.getexif():
            raise ValueError('Orientation changed or EXIF retained')
        if not np.array_equal(a, b):
            raise ValueError('Decoded pixel mismatch')
        pixel_sha = digest(a.tobytes())
    return {'version': VERSION, 'scope': 'generated_only_not_production', **identity,
            'source_sha256': expected_source_sha, 'output_sha256': digest(output),
            'ICC_sha256': digest(profile), 'scan_sha256': digest(scan_before),
            'decoded_RGB_sha256': pixel_sha, 'dimensions_wh': list(size_before),
            'decoded_pixels_equal': True, 'maximum_channel_difference': 0,
            'ICC_bytes_preserved': True, 'metadata_allowlist_passed': True,
            'real_data_authorized': False, 'upload_authorized': False,
            'labels_approved': False}
